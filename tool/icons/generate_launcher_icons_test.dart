// Generates the Android launcher icons of GymLog (M10).
//
//   flutter test tool/icons/generate_launcher_icons_test.dart
//
// Writes PNGs and XML into android/app/src/{main,debug,profile}/res. The
// release app gets a white barbell on plate blue, the DEV app (debug and
// profile build) a dark barbell on plate yellow with "DEV", so both can be
// told apart on the home screen. Drawn with dart:ui, no extra packages.
// Not part of `flutter test` (lives outside test/).
import 'dart:io';
import 'dart:ui' as ui;

import 'package:flutter/painting.dart';
import 'package:flutter/services.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:gymlog/core/theme/palette.dart';

const _densities = {
  'mdpi': 1.0,
  'hdpi': 1.5,
  'xhdpi': 2.0,
  'xxhdpi': 3.0,
  'xxxhdpi': 4.0,
};

/// One app variant.
final class _Variant {
  const _Variant(this.dirs, this.background, this.foreground, {this.label});

  final List<String> dirs;
  final Color background;
  final Color foreground;
  final String? label;
}

const _release = _Variant(['main'], Palette.plateBlue, Palette.white);
const _dev = _Variant(
  ['debug', 'profile'],
  Palette.plateYellow,
  Palette.iron,
  label: 'DEV',
);

String _hex(Color c) =>
    '#${(c.toARGB32() & 0xFFFFFF).toRadixString(16).padLeft(6, '0').toUpperCase()}';

/// The barbell (and label) in the 108 × 108 dp space of an adaptive icon
/// foreground; everything stays inside the 66 dp safe circle.
void _paintSymbol(Canvas canvas, _Variant v) {
  final paint = Paint()..color = v.foreground;
  RRect r(double l, double t, double w, double h, double radius) =>
      RRect.fromRectAndRadius(
        Rect.fromLTWH(l, t, w, h),
        Radius.circular(radius),
      );
  final dy = v.label == null ? 0.0 : -5.0;
  // Bar.
  canvas.drawRRect(r(25, 52 + dy, 58, 4, 2), paint);
  // Big and small plates on both sides.
  for (final (left, top, w, h) in [
    (36.0, 38.0, 7.0, 32.0),
    (65.0, 38.0, 7.0, 32.0),
    (29.5, 44.0, 5.0, 20.0),
    (73.5, 44.0, 5.0, 20.0),
  ]) {
    canvas.drawRRect(r(left, top + dy, w, h, 2), paint);
  }
  if (v.label case final label?) {
    final text = TextPainter(
      text: TextSpan(
        text: label,
        style: TextStyle(
          fontFamily: 'Barlow',
          fontWeight: FontWeight.w700,
          fontSize: 13,
          letterSpacing: 1.5,
          color: v.foreground,
        ),
      ),
      textDirection: TextDirection.ltr,
    )..layout();
    text.paint(canvas, Offset(54 - text.width / 2, 70));
    text.dispose();
  }
}

Future<Uint8List> _png(int size, void Function(Canvas) draw) async {
  final recorder = ui.PictureRecorder();
  draw(Canvas(recorder));
  final image = await recorder.endRecording().toImage(size, size);
  final data = await image.toByteData(format: ui.ImageByteFormat.png);
  image.dispose();
  return data!.buffer.asUint8List();
}

void _write(String path, List<int> bytes) {
  File(path)
    ..parent.createSync(recursive: true)
    ..writeAsBytesSync(bytes);
}

void _writeText(String path, String text) {
  File(path)
    ..parent.createSync(recursive: true)
    ..writeAsStringSync(text);
}

Future<void> _generate(_Variant v) async {
  for (final dir in v.dirs) {
    final res = 'android/app/src/$dir/res';
    for (final MapEntry(key: name, value: scale) in _densities.entries) {
      // Adaptive foreground: 108 dp.
      final fg = (108 * scale).round();
      _write(
        '$res/mipmap-$name/ic_launcher_foreground.png',
        await _png(fg, (c) {
          c.scale(fg / 108);
          _paintSymbol(c, v);
        }),
      );
      // Legacy icon (Android 7): 48 dp, rounded square.
      final legacy = (48 * scale).round();
      _write(
        '$res/mipmap-$name/ic_launcher.png',
        await _png(legacy, (c) {
          c.scale(legacy / 48);
          c.drawRRect(
            RRect.fromRectAndRadius(
              const Rect.fromLTWH(2, 2, 44, 44),
              const Radius.circular(10),
            ),
            Paint()..color = v.background,
          );
          // The 66 dp safe zone of the adaptive symbol onto 44 dp.
          c.translate(24, 24);
          c.scale(44 / 66);
          c.translate(-54, -54);
          _paintSymbol(c, v);
        }),
      );
    }
    _writeText(
      '$res/values/ic_launcher_colors.xml',
      '<?xml version="1.0" encoding="utf-8"?>\n'
          '<!-- Generated by tool/icons/generate_launcher_icons_test.dart -->\n'
          '<resources>\n'
          '    <color name="ic_launcher_background">${_hex(v.background)}'
          '</color>\n'
          '</resources>\n',
    );
  }
}

void main() {
  test('generate launcher icons', () async {
    TestWidgetsFlutterBinding.ensureInitialized();
    final loader = FontLoader('Barlow')
      ..addFont(
        Future.value(
          ByteData.sublistView(
            File('assets/fonts/Barlow-Bold.ttf').readAsBytesSync(),
          ),
        ),
      );
    await loader.load();
    await _generate(_release);
    await _generate(_dev);
    // Adaptive icon (Android 8+) and themed icon (Android 13+).
    const adaptive =
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tool/icons/generate_launcher_icons_test.dart -->\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/ic_launcher_background" />\n'
        '    <foreground android:drawable="@mipmap/ic_launcher_foreground" />\n';
    _writeText(
      'android/app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml',
      '$adaptive</adaptive-icon>\n',
    );
    _writeText(
      'android/app/src/main/res/mipmap-anydpi-v33/ic_launcher.xml',
      '$adaptive'
          '    <monochrome android:drawable="@mipmap/ic_launcher_foreground" />\n'
          '</adaptive-icon>\n',
    );
  });
}
